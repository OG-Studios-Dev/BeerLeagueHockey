#!/usr/bin/env node
/* eslint-disable @typescript-eslint/no-require-imports -- This executable is intentionally Node CommonJS tooling. */
const fs = require('node:fs');
const path = require('node:path');
const { verifyManifest } = require('./verify-rebuild-manifest.cjs');

const root = path.resolve(__dirname, '..');
const repo = path.resolve(root, '../..');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'src/rebuild/screen-manifest.json'), 'utf8'));
const errors = verifyManifest(root, manifest);
if (errors.length) throw new Error(errors.join('\n'));

const mark = (status) => status === 'accepted' ? 'x' : ' ';
const lines = [
  '# Mobile UI Rebuild Checklist', '',
  '> Generated by `node apps/mobile/scripts/generate-rebuild-checklist.cjs` from `apps/mobile/src/rebuild/screen-manifest.json`. Do not edit by hand.', '',
  `Design source: ${manifest.designSource.summary}`, '',
  `Acceptance rule: ${manifest.acceptancePolicy}`, '',
  '## Screen inventory', '',
  '| Done | Phase | Screen file | Routes | Reachability | Implementation evidence | Review status | Owner note |',
  '| --- | --- | --- | --- | --- | --- | --- | --- |',
];
for (const screen of [...manifest.screens].sort((a, b) => a.file.localeCompare(b.file))) {
  const routes = manifest.routes.filter((route) => route.screenId === screen.id).map((route) => `${route.navigator}/${route.name}`).join('<br>') || 'ORPHAN / UNREACHABLE';
  const evidence = `source:${screen.evidence.sourceImplemented ? 'yes' : 'no'}, browser:${screen.evidence.browserReviewed ? 'yes' : 'no'}, iOS:${screen.evidence.iosDeviceAccepted ? 'yes' : 'no'}`;
  lines.push(`| [${mark(screen.status)}] | ${screen.phase} | \`${screen.file}\` | ${routes} | ${screen.reachability} | ${evidence} | ${screen.status} | ${screen.ownerNotes} |`);
}

lines.push('', '## Explicit orphan / unreachable inventory', '');
lines.push(manifest.orphanScreens.length ? manifest.orphanScreens.map((item) => `- ${item}`).join('\n') : '- None. Every `*Screen.tsx` file currently has at least one registered route.');
lines.push('', '## Route registrations', '', '| Navigator | Route | Component | Gate |', '| --- | --- | --- | --- |');
for (const route of [...manifest.routes].sort((a, b) => `${a.navigator}/${a.name}`.localeCompare(`${b.navigator}/${b.name}`))) {
  lines.push(`| ${route.navigator} | ${route.name} | ${route.component} | ${route.gate} |`);
}
lines.push('', '## Release backlog outside this UI scope', '');
for (const item of manifest.releaseBacklog) lines.push(`- [ ] ${item}`);
lines.push('');
const output = path.join(repo, 'docs/MOBILE-UI-REBUILD-CHECKLIST.md');
fs.writeFileSync(output, `${lines.join('\n').trimEnd()}\n`);
console.log(`Wrote ${path.relative(repo, output)} with ${manifest.screens.length} screens and ${manifest.routes.length} routes.`);
